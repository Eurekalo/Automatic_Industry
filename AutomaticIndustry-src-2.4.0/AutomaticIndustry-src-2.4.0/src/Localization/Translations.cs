        /// <summary>Returns the translation table of the requested language.</summary>
        /// <param name="language">Resolved (never <see cref="UiLanguage.Auto"/>) language.</param>
        internal static Dictionary<string, string> For(UiLanguage language)
        {
            switch (language)
            {
                case UiLanguage.ChineseSimplified:
                    return ChineseSimplified;
                case UiLanguage.ChineseTraditional:
                    return ChineseTraditional;
                case UiLanguage.Korean:
                    return Korean;
                case UiLanguage.Japanese:
                    return Japanese;
                default:
                    return English;
            }
        }
